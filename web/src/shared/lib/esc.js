// shared/lib/esc.js — экранирование HTML для всех интерполяций строк из API (CODING 2.5).
// Тексты алиасов и ошибок апстрима могут содержать разметку — экранируем всё.
const esc = s => String(s ?? "").replace(/[&<>"']/g,
  c => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));

export { esc };
